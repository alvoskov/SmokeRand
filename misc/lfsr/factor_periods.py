import sympy
n_ary = [512, 800, 1024, 1600, 320, 32, 48, 64, 96, 128, 160, 192, 256]

def int_to_u64_ary(x):
    txt = "{"
    while x != 0:
        txt += f"0x{x % 2**64:016X}, "
        x >>= 64
    txt += "}"
    return txt

def test_factors(factors, period):
    fprod = 1
    for f in factors:
        if (period == 2**800 - 1 or period == 2**1600 - 1) and f == 5:
            fprod *= f**3
        else:
            fprod *= f
    print(fprod == period)
    assert fprod == period


