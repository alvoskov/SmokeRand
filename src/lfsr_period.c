/**
 * @brief Returns the pointer to the 0-terminated array of exponents
 * for the LFSR maximal period verification.
 * @param n LFSR state size, bits.
 */
static const LargeInt *get_lfsr_exps(size_t n)
{
    if (n == 32) {
        return lfsr32_exps;
    } else if (n == 48) {
        return lfsr48_exps;
    } else if (n == 64) {
        return lfsr64_exps;
    } else if (n == 96) {
        return lfsr96_exps;
    } else if (n == 128) {
        return lfsr128_exps;
    } else if (n == 160) {
        return lfsr160_exps;
    } else if (n == 192) {
        return lfsr192_exps;
    } else if (n == 256) {
        return lfsr256_exps;
    } else if (n == 320) {
        return lfsr320_exps;
    } else if (n == 512) {
        return lfsr512_exps;
    } else if (n == 1024) {
        return lfsr1024_exps;
    } else {
        return NULL;
    }
}


