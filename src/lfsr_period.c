/**
 * @brief Returns the pointer to the 0-terminated array of exponents
 * for the LFSR maximal period verification.
 * @details It returns an array of the \f$ period / p_i \f$ where \f$ p_i \f$
 * are prime divisors of the period. Factorizations of large Fermat numbers
 * \f$ F_k = 2^{2^k} + 1 \f$ used during the \f$ 2^n - 1 \f$ factorization can
 * be found in the next papers:
 *
 * - R.P. Brent. Factorization of the tenth Fermat number // Mathematics of
 *   computation. 1999. V. 68. N 225. P. 429–451
 *   https://doi.org/10.1090/S0025-5718-99-00992-8
 *
 * In 2026 the largest fully factored Fermat number is \f$ F_{11} \f$ so
 * xorshift-like LFSR size is limited to 4096 bits.
 *
 * Some LFSR have state size that corresponds to Mersenne primes, so empty
 * array of divisors is returned in this case:
 *
 * - https://oeis.org/A000043
 *
 * @param n LFSR state size, bits.
 */
static const LargeInt *get_lfsr_exps(size_t n)
{
    static const size_t mersenne_e[] = {
        31,       61,    89,   107,   127,    521,    607,   1279,
        2203,   2281,  3217,  4253,  4423,   9689,   9941,  11213,
        19937, 21701, 23209, 44497, 86243, 110503, 132049, 216091,
        0
    };

    if (n == 32) {
        return lfsr32_exps;
    } else if (n == 48) {
        return lfsr48_exps;
    } else if (n == 64) {
        return lfsr64_exps;
    } else if (n == 96) {
        return lfsr96_exps;
    } else if (n == 128) {
        return lfsr128_exps;
    } else if (n == 160) {
        return lfsr160_exps;
    } else if (n == 192) {
        return lfsr192_exps;
    } else if (n == 255) {
        return lfsr255_exps;
    } else if (n == 256) {
        return lfsr256_exps;
    } else if (n == 320) {
        return lfsr320_exps;
    } else if (n == 512) {
        return lfsr512_exps;
    } else if (n == 800) {
        return lfsr800_exps;
    } else if (n == 1023) {
        return lfsr1023_exps;
    } else if (n == 1024) {
        return lfsr1024_exps;
    } else if (n == 1600) {
        return lfsr1600_exps;
    } else {
        for (size_t i = 0; mersenne_e[i] != 0; i++) {
            if (mersenne_e[i] == n) {
                return lfsr_noexps;
            }
        }
        return NULL;
    }
}


